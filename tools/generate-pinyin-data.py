"""Regenerates src/HD2Mimnt.Application/Search/PinyinData.g.cs.

Requires Python 3 and pypinyin (``pip install pypinyin``). Only the first two
readings of each character are kept to bound the runtime candidate count.
"""
import sys
from collections import defaultdict
from pathlib import Path

from pypinyin import pinyin, Style

OUTPUT = Path(__file__).resolve().parents[1] / "src/HD2Mimnt.Application/Search/PinyinData.g.cs"

groups = defaultdict(list)
for cp in range(0x4E00, 0xA000):
    ch = chr(cp)
    result = pinyin(ch, style=Style.NORMAL, heteronym=True, errors="ignore")
    if not result or not result[0]:
        continue
    readings = []
    for item in result[0]:
        item = item.strip().lower()
        if item and all("a" <= c <= "z" or c == ":" for c in item) and item not in readings:
            readings.append(item)
    if readings:
        groups[tuple(sorted(readings[:2]))].append(ch)

lines = [",".join(readings) + ":" + "".join(chars) for readings, chars in sorted(groups.items())]
with OUTPUT.open("w", encoding="utf-8", newline="\n") as f:
    f.write("// <auto-generated>\n")
    f.write("// Generated from pypinyin %s (up to two readings per character).\n" % __import__("pypinyin").__version__)
    f.write("// Readings are derived from pypinyin (MIT), which uses the Unicode Unihan database.\n")
    f.write("// Do not edit manually; see tools/generate-pinyin-data.py.\n")
    f.write("// </auto-generated>\n")
    f.write("namespace HD2Mimnt.Application.Search;\n\n")
    f.write("internal static partial class PinyinData\n")
    f.write("{\n")
    f.write("    /// <summary>Each line is comma-separated readings, a colon, then the characters.</summary>\n")
    f.write('    internal const string Table = """\n')
    for line in lines:
        f.write(line + "\n")
    f.write('""";\n')
    f.write("}\n")
print("lines", len(lines), "chars", sum(len(v) for v in groups.values()), "->", OUTPUT)
